package com.hotelos.gateway.openapi.schema;

import io.swagger.v3.oas.annotations.media.Schema;
import java.time.Instant;

@Schema(name = "MaintenanceIssue", description = "Reported room maintenance defect or repair ticket")
public record MaintenanceIssueResponse(
        @Schema(description = "Issue ticket unique ID", example = "00000000-0000-0000-0000-000000000070")
        String issueId,
        @Schema(description = "Target room number", example = "115")
        String roomNumber,
        @Schema(description = "Issue defect description", example = "Broken shower handle")
        String description,
        @Schema(description = "Urgency priority", example = "CRITICAL", allowableValues = {"CRITICAL", "HIGH", "NORMAL", "LOW"})
        String priority,
        @Schema(description = "Ticket resolution status", example = "OPEN", allowableValues = {"OPEN", "ASSIGNED", "RESOLVED", "CANCELLED"})
        String status,
        @Schema(description = "Assigned technician name if assigned", example = "Rustam")
        String assignedTechnician,
        @Schema(description = "Creation timestamp", example = "2026-10-10T15:00:00Z")
        Instant createdAt,
        @Schema(description = "Last update timestamp", example = "2026-10-10T15:00:00Z")
        Instant updatedAt,
        @Schema(description = "Origin source of issue", example = "DIRECT", allowableValues = {"DIRECT", "HOUSEKEEPING"})
        String source,
        @Schema(description = "Source reference identifier if generated by housekeeping task", example = "null")
        String sourceReferenceId,
        @Schema(description = "Whether post-repair cleaning is required", example = "true")
        boolean requiresCleaning,
        @Schema(description = "Impact on room operational sellability", example = "OUT_OF_ORDER", allowableValues = {"OUT_OF_ORDER", "MAINTENANCE_REQUIRED", "NONE"})
        String engineeringImpact,
        @Schema(description = "Whether post-work cleanup is awaiting acknowledgement", example = "false")
        boolean cleanupPending,
        @Schema(description = "Timestamp when cleanup was acknowledged", example = "null")
        Instant cleanupAcknowledgedAt
) {}
